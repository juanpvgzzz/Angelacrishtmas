import assert from 'node:assert/strict';
import { createClient } from '@supabase/supabase-js';
process.loadEnvFile('.env');
const url = process.env.PUBLIC_SUPABASE_URL?.trim();
const key = process.env.PUBLIC_SUPABASE_PUBLISHABLE_KEY?.trim();
assert.ok(url && key, 'Faltan variables PUBLIC_SUPABASE');
const db = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
const categories = await db.from('categories').select('id,active');
assert.ifError(categories.error);
assert.ok(categories.data.every(row => row.active));
const products = await db.from('products').select('id,category_id,active,featured');
assert.ifError(products.error);
const visible = new Set(categories.data.map(row => row.id));
assert.ok(products.data.every(row => row.active && visible.has(row.category_id)));
console.log(JSON.stringify({ categories: categories.data.length, products: products.data.length, featured: products.data.filter(row => row.featured).length }));
const members = await db.from('admin_users').select('user_id');
assert.ok(members.error || members.data.length === 0, 'Se expusieron administradores');
console.log('Anonymous administrator access: denied');
const response = await fetch(`${url}/auth/v1/settings`, { headers: { apikey: key, Origin: 'https://ameladesign.vercel.app' } });
assert.ok(response.ok, `Auth settings HTTP ${response.status}`);
console.log('Auth reachable:', response.status, 'CORS:', response.headers.get('access-control-allow-origin'));
